// server/models/DiningTable.js
// Named DiningTable (not Table) because TABLE is a reserved word in SQL.

module.exports = {
  tables: ["dining_tables"],
  statements: [
    `CREATE TABLE dining_tables (
      id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name          VARCHAR2(50) NOT NULL,
      seats         NUMBER(2) NOT NULL,
      is_available  NUMBER(1) DEFAULT 1 NOT NULL,
      CONSTRAINT dtables_name_uq UNIQUE (name),
      CONSTRAINT dtables_seats_ck CHECK (seats >= 1),
      CONSTRAINT dtables_available_ck CHECK (is_available IN (0, 1))
    )`,
  ],
};