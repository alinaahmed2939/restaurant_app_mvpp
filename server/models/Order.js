// server/models/Order.js
// An order has many items, so in a relational database the items go in a
// second table (order_items) that points back to the order.

module.exports = {
  tables: ["orders", "order_items"],
  statements: [
    `CREATE TABLE orders (
      id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id  NUMBER NOT NULL,
      order_type   VARCHAR2(10) NOT NULL,
      table_id     NUMBER,
      pickup_time  VARCHAR2(5),
      total        NUMBER(10,2) NOT NULL,
      status       VARCHAR2(10) DEFAULT 'Pending' NOT NULL,
      created_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT orders_customer_fk FOREIGN KEY (customer_id) REFERENCES users (id),
      CONSTRAINT orders_table_fk FOREIGN KEY (table_id) REFERENCES dining_tables (id),
      CONSTRAINT orders_type_ck CHECK (order_type IN ('Dine-in', 'Takeaway')),
      CONSTRAINT orders_total_ck CHECK (total >= 0),
      CONSTRAINT orders_status_ck CHECK (status IN ('Pending', 'Preparing', 'Ready', 'Served', 'Cancelled'))
    )`,
    `CREATE TABLE order_items (
      id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      order_id      NUMBER NOT NULL,
      menu_item_id  NUMBER NOT NULL,
      quantity      NUMBER(3) NOT NULL,
      unit_price    NUMBER(8,2) NOT NULL,
      note          VARCHAR2(200),
      CONSTRAINT oi_order_fk FOREIGN KEY (order_id) REFERENCES orders (id) ON DELETE CASCADE,
      CONSTRAINT oi_menu_fk FOREIGN KEY (menu_item_id) REFERENCES menu_items (id),
      CONSTRAINT oi_qty_ck CHECK (quantity >= 1),
      CONSTRAINT oi_price_ck CHECK (unit_price >= 0)
    )`,
    `CREATE OR REPLACE TRIGGER orders_updated_trg
    BEFORE UPDATE ON orders
    FOR EACH ROW
    BEGIN
      :NEW.updated_at := SYSTIMESTAMP;
    END;`,
  ],
};