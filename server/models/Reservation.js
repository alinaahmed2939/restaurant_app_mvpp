// server/models/Reservation.js
// created_at is filled automatically by DEFAULT SYSTIMESTAMP.
// updated_at is refreshed automatically by the trigger below (this is the
// same idea as { timestamps: true } in Mongoose).

module.exports = {
  tables: ["reservations"],
  statements: [
    `CREATE TABLE reservations (
      id                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      customer_id       NUMBER NOT NULL,
      table_id          NUMBER NOT NULL,
      reservation_date  DATE NOT NULL,
      time_slot         VARCHAR2(5) NOT NULL,
      party_size        NUMBER(2) NOT NULL,
      contact_phone     VARCHAR2(15) NOT NULL,
      status            VARCHAR2(10) DEFAULT 'Pending' NOT NULL,
      created_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      updated_at        TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
      CONSTRAINT res_customer_fk FOREIGN KEY (customer_id) REFERENCES users (id),
      CONSTRAINT res_table_fk FOREIGN KEY (table_id) REFERENCES dining_tables (id),
      CONSTRAINT res_party_ck CHECK (party_size BETWEEN 1 AND 12),
      CONSTRAINT res_status_ck CHECK (status IN ('Pending', 'Accepted', 'Declined', 'Cancelled'))
    )`,
    `CREATE OR REPLACE TRIGGER reservations_updated_trg
    BEFORE UPDATE ON reservations
    FOR EACH ROW
    BEGIN
      :NEW.updated_at := SYSTIMESTAMP;
    END;`,
  ],
};