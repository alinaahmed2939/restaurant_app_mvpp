// server/models/MenuItem.js

module.exports = {
  tables: ["menu_items"],
  statements: [
    `CREATE TABLE menu_items (
      id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      name          VARCHAR2(100) NOT NULL,
      description   VARCHAR2(500),
      price         NUMBER(8,2) NOT NULL,
      category      VARCHAR2(20) NOT NULL,
      image         VARCHAR2(50 CHAR),
      is_special    NUMBER(1) DEFAULT 0 NOT NULL,
      is_available  NUMBER(1) DEFAULT 1 NOT NULL,
      CONSTRAINT menu_price_ck CHECK (price >= 0),
      CONSTRAINT menu_category_ck CHECK (category IN ('Starters', 'Mains', 'Desserts', 'Drinks')),
      CONSTRAINT menu_special_ck CHECK (is_special IN (0, 1)),
      CONSTRAINT menu_available_ck CHECK (is_available IN (0, 1))
    )`,
  ],
};